#!/usr/bin/env python3
"""Generates the program icons from the >_SCS logo (5 x 7 pixel glyphs):
  scs/icon.py                 window icon of the desktop app (PNG, Base64)
  packaging/windows/scs.ico   icon of the Windows program and installer
  packaging/linux/scs.png     icon of the Linux menu entry
Needs Pillow (pip install pillow); only required when the logo changes."""
import base64
import io
import os

GLYPHS = {
    ">": ["x....", ".x...", "..x..", "...x.", "..x..", ".x...", "x...."],
    "_": [".....", ".....", ".....", ".....", ".....", ".....", "xxxxx"],
    "S": [".xxxx", "x....", "x....", ".xxx.", "....x", "....x", "xxxx."],
    "C": [".xxxx", "x....", "x....", "x....", "x....", "x....", ".xxxx"],
}


def logo_pixels(text=">_SCS"):
    px = []
    for i, ch in enumerate(text):
        for y, row in enumerate(GLYPHS[ch]):
            for x, c in enumerate(row):
                if c == "x":
                    px.append((i * 6 + x, y))
    return px, len(text) * 6 - 1, 7


def render(size):
    from PIL import Image, ImageDraw
    px, w, h = logo_pixels()
    img = Image.new("RGBA", (size, size), (0, 0, 0, 255))
    scale = max(1, size // (w + 4))
    ox, oy = (size - w * scale) // 2, (size - h * scale) // 2
    d = ImageDraw.Draw(img)
    for x, y in px:
        d.rectangle([ox + x * scale, oy + y * scale, ox + (x + 1) * scale - 1, oy + (y + 1) * scale - 1], fill=(0, 255, 0, 255))
    return img


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    buf = io.BytesIO()
    render(64).save(buf, "PNG", optimize=True)
    b64 = base64.b64encode(buf.getvalue()).decode()
    lines = [b64[i:i + 100] for i in range(0, len(b64), 100)]
    with open(os.path.join(root, "scs", "icon.py"), "w", encoding="utf-8") as fh:
        fh.write('"""Window icon (the >_SCS logo, PNG). Generated by tools/make_icons.py."""\n\nICON_PNG = (\n'
                 + "".join(f'    "{ln}"\n' for ln in lines) + ")\n")
    os.makedirs(os.path.join(root, "packaging", "linux"), exist_ok=True)
    render(128).convert("RGB").save(os.path.join(root, "packaging", "linux", "scs.png"), optimize=True)
    os.makedirs(os.path.join(root, "packaging", "windows"), exist_ok=True)
    render(256).save(os.path.join(root, "packaging", "windows", "scs.ico"),
                     sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    print("scs/icon.py, packaging/windows/scs.ico and packaging/linux/scs.png written")


if __name__ == "__main__":
    main()
